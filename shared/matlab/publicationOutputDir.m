function outputDir = publicationOutputDir(publicationId,createDirectory)
%PUBLICATIONOUTPUTDIR Resolve the canonical build directory for an item.

if nargin < 2
    createDirectory = true;
end

id = lower(strrep(string(publicationId),'\','/'));
legacy = containers.Map( ...
    {'figure1','figure2','figure3','figure4', ...
     'supp_figure1','supp_figure2','supp_figure3','supp_figure4', ...
     'supp_figure5','supp_figure6','supp_figure8','supp_figure9', ...
     'supp_figure10','supp_figure11','supp_figure12','supp_figure13', ...
     'supp_figure14','supp_figure15'}, ...
    {'main/figure1','main/figure2','main/figure3','main/figure4', ...
     'supplementary/note1','supplementary/figure1', ...
     'extended_data/figure1','extended_data/figure2', ...
     'supplementary/note2','extended_data/figure3', ...
     'extended_data/figure4','supplementary/figure3', ...
     'extended_data/figure5','extended_data/figure6', ...
     'supplementary/figure4','extended_data/figure7', ...
     'extended_data/figure8','extended_data/figure9'});

key = char(id);
if isKey(legacy,key)
    id = string(legacy(key));
end
parts = split(id,'/');
parts(parts == "") = [];
outputDir = fullfile(projectRoot(),'build','figures',parts{:});
if createDirectory && ~isfolder(outputDir)
    mkdir(outputDir);
end
end
