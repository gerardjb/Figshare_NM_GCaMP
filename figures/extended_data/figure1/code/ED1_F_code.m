function ED1_F_code
%%%
% Plots effects of magnesium on kinetics across sensors as in the indicated
% figure
%%%

% Close any open plots
close all

% Open data files
d = fullfile(fileparts(mfilename('fullpath')),'..','inputs');

%Specifying the files for each construct/buffer composition
Kfiles = {[d,filesep,'OnSummary20210129_On 37 K - 0nM_G6f.mat'],...
    [d,filesep,'OnSummary20200711_On 37 K - 0nM_jG7f.mat'],...
    [d,filesep,'OnSummary20210129_On 37 K - 0nM_jG8f.mat'],...
                };
Ifiles = {[d,filesep,'OnSummary20210129_On 37 I - 0nM_G6f.mat'],...
    [d,filesep,'OnSummary20200711_On 37 I - 0nM_jG7f.mat'],...
    [d,filesep,'OnSummary20210129_On 37 I - 0nM_jG8f.mat'],...
                };
IMfiles = {[d,filesep,'OnSummary20210129_On 37 I+ - 0nM_G6f.mat'],...
    [d,filesep,'OnSummary20210129_On 37 I+ - 0nM_jG7f.mat'],...
    [d,filesep,'OnSummary20210129_On 37 I+ - 0nM_jG8f.mat'],...
    };

%Set up the figure to contain the plots
f =figure;
sizerRaw = [6.25,2];
set(f,'Paperunits','inches',...
    'Papersize',sizerRaw,...
    'Paperposition',[0,0,sizerRaw],...
    'Units','inches',...
    'Position',[2,2,sizerRaw]);
t = tiledlayout(1,3);
conds = {'no Mg^{2+}','Mg^{2+}+'};

for i = 1:length(Kfiles)
    msize = 12;
    nexttile;
    hold on;set(gca,'tickdir','out');
    load(Kfiles{i});
    GCaMP = GCaMPalias(const);
    cmap = hex2rgb(pickGCaMPcolorsMS(const))*0.4;
    goodPts = t_50out(:,3)>0.05;
    plot(t_50out(goodPts,1)/1000,t_50out(goodPts,2)*1000,...
        'marker','.','markersize',msize,'markerfacecolor',cmap,...
        'Linewidth',1,'color',cmap);
    text(t_50out(find(goodPts,1),1)/1000+0.1,t_50out(find(goodPts,1),2)*1000,...
        conds{1},'color',cmap,...
        'Horizontalalignment','left','verticalalignment','bottom');
    
    
    load(IMfiles{i});
    cmap = pickGCaMPcolorsMS(const);
    goodPts = t_50out(:,3)>0.05;
    plot(t_50out(goodPts,1)/1000,t_50out(goodPts,2)*1000,...
        'marker','.','markersize',msize,'markerfacecolor',cmap,...
        'Linewidth',1,'color',cmap);
    text(t_50out(find(goodPts,1),1)/1000+0.1,...
        t_50out(find(goodPts,1),2)*1000-0.15*(t_50out(find(goodPts,1),2)*1000),...
        conds{2},'color',cmap,...
        'Horizontalalignment','right','verticalalignment','top');
    
    h = gca;
    set(h,'Yscale','log','Xscale','log',...
        'linewidth',1,...
        'fontname','arial','fontsize',12)
    ylabel('Half rise time (ms)')
    xlabel('free [Ca^{2+}] (\muM)')
    set(h,'xlim',[0.04,50],'xtick',[0.1,1,10],...
        'ylim',[1,2000],'ytick',[1,10,100,1000]);
    set(h,...
        'fontsize',8);
    %grid on
    title(GCaMPalias(const),'color',pickGCaMPcolorsMS(const),'fontname','arial',...
        'fontsize',10,'fontweight','normal');%'fontstyle','plain');
    %set(gca,'fontname','arial');
%     set(gcf,'Units','points');
%     set(gcf,'Position',[0,0,240,180]);
end

saveFigureOutputs("extended_data/figure1","ED1_F");
