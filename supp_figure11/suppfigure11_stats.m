    panel_B_table, struct( ...
        'analysis_id', "panel_B_false_positive", ...
        'response_variable', "FPCount", ...
        'response_definition', "False-positive MAP events per epoch", ...
        'formula', "FPCount ~ Method*GTSpikeBin + " + ...
            "(1|CellID) + (1|CellEpochID) + (1|ObservationID)", ...
        'distribution', "Poisson", ...
        'link', "log", ...
        'bin_variable', "GTSpikeBin", ...
        'offset_variable', "LogEpochDuration", ...
        'offset_definition', "Natural logarithm of epoch duration in seconds", ...
        'binomial_size_variable', "", ...
        'overdispersion_model', ...
            "Observation-level random intercept (Poisson-lognormal GLMM)"), ...
    stats.reference_methods);

panel_B.false_negative = fitAnalysis( ...
    panel_B_table(panel_B_table.GTSpikes > 0, :), struct( ...
        'analysis_id', "panel_B_false_negative", ...
        'response_variable', "FNCount", ...
        'response_definition', ...
            "False-negative ground-truth spikes / all ground-truth spikes", ...
        'formula', "FNCount ~ Method*GTSpikeBin + " + ...
            "(1|CellID) + (1|CellEpochID)", ...
        'distribution', "Binomial", ...
        'link', "logit", ...
        'bin_variable', "GTSpikeBin", ...
        'offset_variable', "", ...
        'offset_definition', "None", ...
        'binomial_size_variable', "GTSpikes", ...
        'overdispersion_model', ...
            "Cell and cell-epoch random intercepts"), ...
    stats.reference_methods);
stats.panel_B = panel_B;

panel_C = struct();
panel_C.panel = "C";
panel_C.title = "Spike history versus error type";
panel_C.history_window_s = unique(panel_C_table.HistoryWindowS);
panel_C.bin_variable = "HistoryBin";
panel_C.bin_levels = string(categories(panel_C_table.HistoryBin));
panel_C.n_rows = height(panel_C_table);
panel_C.n_cells = numel(categories(panel_C_table.CellID));
panel_C.n_cell_epochs = numel(categories(panel_C_table.CellEpochID));
panel_C.summary = summarizePanelC(panel_C_table);

panel_C_fp_table = panel_C_table(panel_C_table.ExposureSeconds > 0, :);
panel_C.false_positive = fitAnalysis( ...
    panel_C_fp_table, struct( ...
        'analysis_id', "panel_C_false_positive", ...
        'response_variable', "FPCount", ...
        'response_definition', ...
            "False-positive MAP events during exposure to a history bin", ...
        'formula', "FPCount ~ Method*HistoryBin + " + ...
            "(1|CellID) + (1|CellEpochID) + (1|ObservationID)", ...
        'distribution', "Poisson", ...
        'link', "log", ...
        'bin_variable', "HistoryBin", ...
        'offset_variable', "LogExposureSeconds", ...
        'offset_definition', ...
            "Natural logarithm of time in the history bin (seconds)", ...
        'binomial_size_variable', "", ...
        'overdispersion_model', ...
            "Observation-level random intercept (Poisson-lognormal GLMM)"), ...
    stats.reference_methods);

panel_C_fn_table = panel_C_table(panel_C_table.GTCount > 0, :);
panel_C.false_negative = fitAnalysis( ...
    panel_C_fn_table, struct( ...
        'analysis_id', "panel_C_false_negative", ...
        'response_variable', "FNCount", ...
        'response_definition', ...
            "False-negative ground-truth spikes / ground-truth spikes in a history bin", ...
        'formula', "FNCount ~ Method*HistoryBinFNStats + " + ...
            "(1|CellID) + (1|CellEpochID)", ...
        'distribution', "Binomial", ...
        'link', "logit", ...
        'bin_variable', "HistoryBinFNStats", ...
        'offset_variable', "", ...
        'offset_definition', "None", ...
        'binomial_size_variable', "GTCount", ...
        'overdispersion_model', ...
            "Cell and cell-epoch random intercepts"), ...
    stats.reference_methods);
stats.panel_C = panel_C;

mat_file = fullfile(output_dir, 'suppfigure11_stats.mat');
save(mat_file, 'stats', '-v7.3');

coefficient_table = collectCoefficientTables(stats);
test_table = collectTestTables(stats);
latent_effect_size_table = test_table( ...
    ismember(test_table.Test, ["method_difference_within_bin", ...
        "average_method_difference_across_bins"]), ...
    {'Analysis', 'ReferenceMethod', 'ComparisonMethod', ...
    'Distribution', 'Link', 'Test', 'Bin', 'Estimate', ...
    'EstimateLower', 'EstimateUpper', 'ExponentiatedEstimate', ...
    'LatentScaleD', 'LatentScaleDLower', 'LatentScaleDUpper', ...
    'LatentScaleSD', 'DistributionSpecificVariance', ...
    'ObservationLevelVariance', 'PoissonMeanCount', ...
    'LatentScaleMethod', 'F', 'DF1', 'DF2', 'pValue'});
