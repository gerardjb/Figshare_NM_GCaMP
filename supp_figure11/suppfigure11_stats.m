function coefficient_table = collectCoefficientTables(stats)
analyses = getAnalyses(stats);
tables = cell(0, 1);
for analysis_index = 1:numel(analyses)
    analysis = analyses{analysis_index};
    for reference_index = 1:numel(analysis.glme_by_reference)
        reference_stats = analysis.glme_by_reference{reference_index};
        coefficients = reference_stats.coefficients;
        if isa(coefficients, 'dataset')
            coefficients = dataset2table(coefficients);
        end
        n_coefficients = height(coefficients);
        coefficient_names = coefficientNamesFromTable(coefficients);
        output = table( ...
            repmat(analysis.analysis_id, n_coefficients, 1), ...
            repmat(reference_stats.reference_method, n_coefficients, 1), ...
            repmat(analysis.distribution, n_coefficients, 1), ...
            repmat(analysis.link, n_coefficients, 1), ...
            coefficient_names, ...
            coefficients.Estimate, ...
            exp(coefficients.Estimate), ...
            coefficients.SE, ...
            coefficients.tStat, ...
            coefficients.DF, ...
            coefficients.pValue, ...
            coefficients.Lower, ...
            coefficients.Upper, ...
            'VariableNames', {'Analysis', 'ReferenceMethod', ...
            'Distribution', 'Link', 'Coefficient', ...
            'Estimate', 'ExponentiatedEstimate', ...
            'SE', 'tStat', 'DF', 'pValue', 'Lower', 'Upper'});
        tables{end + 1} = output; %#ok<AGROW>
    end
end
coefficient_table = vertcat(tables{:});
end


function names = coefficientNamesFromTable(coefficients)
if ismember('Name', coefficients.Properties.VariableNames)
    names = string(coefficients.Name);
elseif ~isempty(coefficients.Properties.RowNames)
    names = string(coefficients.Properties.RowNames);
else
    names = "coefficient_" + string((1:height(coefficients))');
end
end


function test_table = collectTestTables(stats)
analyses = getAnalyses(stats);
rows = repmat(struct( ...
    'Analysis', "", 'ReferenceMethod', "", ...
    'ComparisonMethod', "", 'Distribution', "", 'Link', "", ...
    'ExponentiatedEffectType', "", 'Test', "", 'Bin', "", ...
    'Estimate', NaN, 'EstimateLower', NaN, 'EstimateUpper', NaN, ...
    'ExponentiatedEstimate', NaN, ...
    'LatentScaleD', NaN, 'LatentScaleDLower', NaN, ...
    'LatentScaleDUpper', NaN, 'LatentScaleSD', NaN, ...
    'DistributionSpecificVariance', NaN, ...
    'ObservationLevelVariance', NaN, 'PoissonMeanCount', NaN, ...
    'LatentScaleMethod', "", ...
    'NTerms', NaN, 'F', NaN, 'DF1', NaN, 'DF2', NaN, ...
    'pValue', NaN), 0, 1);
for analysis_index = 1:numel(analyses)
    analysis = analyses{analysis_index};
    for reference_index = 1:numel(analysis.glme_by_reference)
        reference_stats = analysis.glme_by_reference{reference_index};
        comparisons = reference_stats.comparison_tests;
        for comparison_index = 1:numel(comparisons)
            comparison = comparisons(comparison_index);
            rows(end + 1) = testRow(analysis, comparison, ...
                "main_effect_at_reference_bin", "", ...
                comparison.main_effect_at_reference_bin); %#ok<AGROW>
            rows(end + 1) = testRow(analysis, comparison, ...
                "interaction_joint", "", ...
                comparison.interaction_joint); %#ok<AGROW>
            rows(end + 1) = testRow(analysis, comparison, ...
                "overall_method_difference_joint", "", ...
                comparison.overall_method_difference_joint); %#ok<AGROW>
            rows(end + 1) = testRow(analysis, comparison, ...
                "average_method_difference_across_bins", ...
                comparison.average_across_bins.bin, ...
                comparison.average_across_bins); %#ok<AGROW>
            for bin_index = 1:numel(comparison.difference_by_bin)
                bin_test = comparison.difference_by_bin(bin_index);
                rows(end + 1) = testRow(analysis, comparison, ...
                    "method_difference_within_bin", bin_test.bin, ...
                    bin_test); %#ok<AGROW>
            end
        end
    end
end
test_table = struct2table(rows);
end


function row = testRow(analysis, comparison, test_name, bin, result)
if analysis.distribution == "Poisson"
    effect_type = "Rate ratio";
else
    effect_type = "Odds ratio";
end
row = struct( ...
    'Analysis', analysis.analysis_id, ...
    'ReferenceMethod', comparison.reference_method, ...
    'ComparisonMethod', comparison.comparison_method, ...
    'Distribution', analysis.distribution, ...
    'Link', analysis.link, ...
    'ExponentiatedEffectType', effect_type, ...
    'Test', test_name, ...
    'Bin', bin, ...
    'Estimate', NaN, ...
    'EstimateLower', NaN, ...
    'EstimateUpper', NaN, ...
    'ExponentiatedEstimate', NaN, ...
    'LatentScaleD', NaN, ...
    'LatentScaleDLower', NaN, ...
    'LatentScaleDUpper', NaN, ...
    'LatentScaleSD', NaN, ...
    'DistributionSpecificVariance', NaN, ...
    'ObservationLevelVariance', NaN, ...
    'PoissonMeanCount', NaN, ...
    'LatentScaleMethod', "", ...
    'NTerms', result.n_terms, ...
    'F', result.F, ...
    'DF1', result.df1, ...
    'DF2', result.df2, ...
    'pValue', result.p);
if isfield(result, 'link_scale_estimate')
    row.Estimate = result.link_scale_estimate;
    row.ExponentiatedEstimate = result.exponentiated_estimate;
end
if isfield(result, 'link_scale_lower')
    row.EstimateLower = result.link_scale_lower;
    row.EstimateUpper = result.link_scale_upper;
end
if isfield(result, 'latent_scale_d')
    row.LatentScaleD = result.latent_scale_d;
    row.LatentScaleDLower = result.latent_scale_d_lower;
    row.LatentScaleDUpper = result.latent_scale_d_upper;
    row.LatentScaleSD = result.latent_scale_sd;
    row.DistributionSpecificVariance = ...
        result.distribution_specific_variance;
    row.ObservationLevelVariance = ...
        result.observation_level_variance;
    row.PoissonMeanCount = result.poisson_mean_count;
    row.LatentScaleMethod = result.latent_scale_method;
end
end


