function T = preparePanelBTable(T, method_order)
T.Method = categorical(normalizeMethodNames(T.Method));
T.Method = reordercats(T.Method, cellstr(method_order));
bin_order = "Q" + string(1:6);
T.GTSpikeBin = categorical(string(T.GTSpikeBin), bin_order, ...
    'Ordinal', true);
T.CellID = categorical(T.CellID);
T.CellEpochID = categorical(T.CellEpochID);
T.ObservationID = categorical(compose("B_obs_%04d", (1:height(T))'));
T.LogEpochDuration = log(double(T.EpochDurationS));
T.FNFraction = double(T.FNCount) ./ double(T.GTSpikes);
end


function T = preparePanelCTable(T, method_order)
T.Method = categorical(normalizeMethodNames(T.Method));
T.Method = reordercats(T.Method, cellstr(method_order));
bin_order = ["0", "1", "2", "3-4", "5-8", "9+"];
T.HistoryBin = categorical(string(T.HistoryBin), bin_order, ...
    'Ordinal', true);
fn_stats_bin = string(T.HistoryBin);
fn_stats_bin(ismember(fn_stats_bin, ["5-8", "9+"])) = "5+";
fn_stats_bin_order = ["0", "1", "2", "3-4", "5+"];
T.HistoryBinFNStats = categorical(fn_stats_bin, ...
    fn_stats_bin_order, 'Ordinal', true);
T.CellID = categorical(T.CellID);
T.CellEpochID = categorical(T.CellEpochID);
T.ObservationID = categorical(compose("C_obs_%04d", (1:height(T))'));
T.LogExposureSeconds = log(double(T.ExposureSeconds));
T.FNFraction = double(T.FNCount) ./ double(T.GTCount);
end


function normalized = normalizeMethodNames(method_names)
normalized = replace(string(method_names), "Biophys SMC", "Biophys_SMC");
normalized = replace(normalized, "BiophysSMC", "Biophys_SMC");
end


function analysis = fitAnalysis(T, specification, reference_methods)
analysis = specification;
analysis.dummy_var_coding = "reference";
bin_categories = categories(T.(specification.bin_variable));
analysis.reference_bin = string(bin_categories{1});
analysis.n_rows = height(T);
analysis.n_cells = numel(categories(T.CellID));
analysis.n_cell_epochs = numel(categories(T.CellEpochID));
analysis.method_levels = string(categories(T.Method));
analysis.bin_levels = string(categories(T.(specification.bin_variable)));
analysis.reference_methods = reference_methods;
analysis.df_method = [ ...
    "fitglme/coefTest residual degrees of freedom; " + ...
    "Satterthwaite is not available for these GLMMs"];
analysis.glme_by_reference = cell(numel(reference_methods), 1);

T.Method = removecats(T.Method);
T.CellID = removecats(T.CellID);
T.CellEpochID = removecats(T.CellEpochID);
if ismember('ObservationID', T.Properties.VariableNames)
    T.ObservationID = removecats(T.ObservationID);
end
T.(specification.bin_variable) = ...
    removecats(T.(specification.bin_variable));

for reference_index = 1:numel(reference_methods)
    reference_method = reference_methods(reference_index);
    if ~ismember(reference_method, analysis.method_levels)
        error('suppfigure11_stats:ReferenceMethod', ...
            'Reference method %s is absent from %s.', ...
            reference_method, specification.analysis_id);
    end

    T_reference = T;
    current_order = string(categories(T_reference.Method));
    new_order = [reference_method; ...
        current_order(current_order ~= reference_method)];
    T_reference.Method = reordercats( ...
        T_reference.Method, cellstr(new_order));

    arguments = { ...
        'Distribution', char(specification.distribution), ...
        'Link', char(specification.link), ...
        'DummyVarCoding', 'reference'};
    if strlength(specification.offset_variable) > 0
        arguments = [arguments, {'Offset', ...
            T_reference.(specification.offset_variable)}]; %#ok<AGROW>
    end
    if strlength(specification.binomial_size_variable) > 0
        arguments = [arguments, {'BinomialSize', ...
            T_reference.(specification.binomial_size_variable)}]; %#ok<AGROW>
    end

    glme = fitglme(T_reference, char(specification.formula), ...
        arguments{:});
    [beta, ~, beta_stats] = fixedEffects(glme);

    reference_stats = struct();
    reference_stats.reference_method = reference_method;
    reference_stats.glme = glme;
    reference_stats.coefficient_names = string(glme.CoefficientNames);
    reference_stats.fixed_effect_estimates = beta;
    reference_stats.fixed_effect_names = ...
        reference_stats.coefficient_names;
    reference_stats.fixed_effect_stats = beta_stats;
    reference_stats.coefficients = glme.Coefficients;
    reference_stats.model_criteria = glme.ModelCriterion;
    reference_stats.log_likelihood = glme.LogLikelihood;
    reference_stats.residual_df = glme.DFE;
    reference_stats.anova = anova(glme);
    reference_stats.random_effects = randomEffects(glme);
    reference_stats.covariance_parameters = covarianceParameters(glme);

    comparison_methods = analysis.method_levels( ...
        analysis.method_levels ~= reference_method);
    reference_stats.comparison_tests = buildReferenceTests( ...
        glme, T_reference, specification, reference_method, ...
        comparison_methods, analysis.bin_levels);
    analysis.glme_by_reference{reference_index} = reference_stats;
end
end


function comparison_tests = buildReferenceTests( ...
        glme, T, specification, reference_method, ...
        comparison_methods, bin_levels)
coef_names = string(glme.CoefficientNames);
bin_variable = specification.bin_variable;
comparison_tests = struct([]);

for comparison_index = 1:numel(comparison_methods)
    comparison_method = comparison_methods(comparison_index);
    main_term = "Method_" + comparison_method;
    main_mask = coef_names == main_term;
    interaction_mask = methodInteractionMask( ...
        coef_names, comparison_method, bin_variable);
    overall_mask = main_mask | interaction_mask;

    this_test = struct();
    this_test.reference_method = reference_method;
    this_test.comparison_method = comparison_method;
    this_test.direction = [ ...
        "Positive link-scale estimates indicate a higher response for " + ...
        comparison_method + " than " + reference_method + "."];
    this_test.main_effect_at_reference_bin = ...
        runCoefficientTest(glme, double(main_mask));
    this_test.interaction_joint = ...
        runJointCoefficientTest(glme, interaction_mask);
    this_test.overall_method_difference_joint = ...
        runJointCoefficientTest(glme, overall_mask);
    this_test.average_across_bins = buildAverageBinContrast( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_levels);
    this_test.difference_by_bin = buildBinContrasts( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_levels);
    if isempty(comparison_tests)
        comparison_tests = this_test;
    else
        comparison_tests(end + 1, 1) = this_test; %#ok<AGROW>
    end
end
end


function result = buildAverageBinContrast( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_levels)
coefficient_names = string(glme.CoefficientNames);
n_bins = numel(bin_levels);
H = zeros(1, numel(coefficient_names));
distribution_variances = nan(n_bins, 1);
observation_variances = nan(n_bins, 1);
poisson_means = nan(n_bins, 1);
latent_method = "";

for bin_index = 1:n_bins
    L = buildMethodContrast( ...
        coefficient_names, comparison_method, ...
        specification.bin_variable, bin_levels(bin_index), ...
        bin_index == 1);
    H = H + L / n_bins;
    [~, distribution_variances(bin_index), ...
        observation_variances(bin_index), ...
        poisson_means(bin_index), latent_method] = ...
        getLatentScaleComponents(glme, T, specification, ...
        reference_method, comparison_method, bin_levels(bin_index));
end

result = runCoefficientTest(glme, H);
result.bin = "All bins (equal weight)";
result.latent_scale_sd = sqrt( ...
    mean(distribution_variances, 'omitnan') + ...
    mean(observation_variances, 'omitnan'));
result.latent_scale_d = result.link_scale_estimate / ...
    result.latent_scale_sd;
result.latent_scale_d_lower = result.link_scale_lower / ...
    result.latent_scale_sd;
result.latent_scale_d_upper = result.link_scale_upper / ...
    result.latent_scale_sd;
result.distribution_specific_variance = ...
    mean(distribution_variances, 'omitnan');
result.observation_level_variance = ...
    mean(observation_variances, 'omitnan');
result.poisson_mean_count = mean(poisson_means, 'omitnan');
result.latent_scale_method = ...
    "Equal-bin average contrast; " + latent_method;
end


function bin_tests = buildBinContrasts( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_levels)
coef_names = string(glme.CoefficientNames);
beta = glme.Coefficients.Estimate;
bin_tests = struct([]);
bin_variable = specification.bin_variable;

for bin_index = 1:numel(bin_levels)
    L = buildMethodContrast(coef_names, comparison_method, ...
        bin_variable, bin_levels(bin_index), bin_index == 1);
    result = runCoefficientTest(glme, L);
    result.bin = bin_levels(bin_index);
    result.link_scale_estimate = L * beta;
    result.exponentiated_estimate = exp(result.link_scale_estimate);
    result = addLatentEffectSize(result, glme, T, specification, ...
        reference_method, comparison_method, bin_levels(bin_index));
    if isempty(bin_tests)
        bin_tests = result;
    else
        bin_tests(end + 1, 1) = result; %#ok<AGROW>
    end
end
end


function L = buildMethodContrast( ...
        coefficient_names, comparison_method, ...
        bin_variable, bin_label, is_reference_bin)
main_term = "Method_" + comparison_method;
L = double(coefficient_names == main_term);
if is_reference_bin
    return
end
interaction_term_a = main_term + ":" + ...
    bin_variable + "_" + bin_label;
interaction_term_b = bin_variable + "_" + ...
    bin_label + ":" + main_term;
L = L + double(coefficient_names == interaction_term_a | ...
    coefficient_names == interaction_term_b);
end


function mask = methodInteractionMask( ...
        coefficient_names, comparison_method, bin_variable)
method_term = "Method_" + comparison_method;
bin_term = bin_variable + "_";
mask = ...
    (startsWith(coefficient_names, method_term + ":") & ...
        contains(coefficient_names, bin_term)) | ...
    (startsWith(coefficient_names, bin_term) & ...
        endsWith(coefficient_names, ":" + method_term));
end


function test_stats = runCoefficientTest(glme, L)
test_stats = struct( ...
    'n_terms', nnz(L), ...
    'coefficient_mask', logical(L), ...
    'link_scale_estimate', NaN, ...
    'link_scale_se', NaN, ...
    'link_scale_lower', NaN, ...
    'link_scale_upper', NaN, ...
    'exponentiated_estimate', NaN, ...
    'p', NaN, 'F', NaN, 'df1', NaN, 'df2', NaN);
if nnz(L) == 0
    return
end
[beta, ~, ~] = fixedEffects(glme);
L = reshape(L, 1, []);
test_stats.link_scale_estimate = L * beta;
test_stats.link_scale_se = sqrt(L * glme.CoefficientCovariance * L');
critical_value = tinv(0.975, glme.DFE);
test_stats.link_scale_lower = test_stats.link_scale_estimate - ...
    critical_value * test_stats.link_scale_se;
test_stats.link_scale_upper = test_stats.link_scale_estimate + ...
    critical_value * test_stats.link_scale_se;
test_stats.exponentiated_estimate = ...
    exp(test_stats.link_scale_estimate);
[p, F, df1, df2] = coefTest(glme, L);
test_stats.p = p;
test_stats.F = F;
test_stats.df1 = df1;
test_stats.df2 = df2;
end


function result = addLatentEffectSize( ...
        result, glme, T, specification, reference_method, ...
        comparison_method, bin_label)
result.latent_scale_d = NaN;
result.latent_scale_d_lower = NaN;
result.latent_scale_d_upper = NaN;
result.latent_scale_sd = NaN;
result.distribution_specific_variance = NaN;
result.observation_level_variance = 0;
result.poisson_mean_count = NaN;
result.latent_scale_method = "";
[result.latent_scale_sd, ...
    result.distribution_specific_variance, ...
    result.observation_level_variance, ...
    result.poisson_mean_count, ...
    result.latent_scale_method] = getLatentScaleComponents( ...
    glme, T, specification, reference_method, ...
    comparison_method, bin_label);
result.latent_scale_d = result.link_scale_estimate / ...
    result.latent_scale_sd;
result.latent_scale_d_lower = result.link_scale_lower / ...
    result.latent_scale_sd;
result.latent_scale_d_upper = result.link_scale_upper / ...
    result.latent_scale_sd;
end


function [latent_sd, distribution_variance, ...
        observation_variance, poisson_mean, method] = ...
        getLatentScaleComponents( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_label)
observation_variance = 0;
poisson_mean = NaN;

if specification.distribution == "Binomial"
    distribution_variance = pi^2 / 3;
    method = "Chinn conversion: log(OR) / sqrt(pi^2/3)";
elseif specification.distribution == "Poisson"
    poisson_mean = getPoissonMeanCount( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_label);
    distribution_variance = log(1 + 1 / poisson_mean);
    observation_variance = ...
        getObservationLevelVariance(glme, specification);
    method = [ ...
        "Nakagawa lognormal approximation: log(RR) / " + ...
        "sqrt(log(1 + 1/lambda_bar) + OLRE variance)"];
else
    error('suppfigure11_stats:LatentDistribution', ...
        'No latent-scale conversion is defined for %s.', ...
        specification.distribution);
end
latent_sd = sqrt(distribution_variance + observation_variance);
end


function lambda_bar = getPoissonMeanCount( ...
        glme, T, specification, reference_method, ...
        comparison_method, bin_label)
is_template = string(T.Method) == reference_method & ...
    string(T.(specification.bin_variable)) == bin_label;
template = T(is_template, :);
if isempty(template)
    error('suppfigure11_stats:PoissonTemplate', ...
        'No reference observations exist for bin %s.', bin_label);
end

method_categories = categories(T.Method);
reference_table = template;
comparison_table = template;
reference_table.Method = categorical( ...
    repmat(reference_method, height(template), 1), method_categories);
comparison_table.Method = categorical( ...
    repmat(comparison_method, height(template), 1), method_categories);
offset_reference = reference_table.(specification.offset_variable);
offset_comparison = comparison_table.(specification.offset_variable);
mu_reference = predict(glme, reference_table, ...
    'Conditional', false, 'Offset', offset_reference);
mu_comparison = predict(glme, comparison_table, ...
    'Conditional', false, 'Offset', offset_comparison);
lambda_bar = mean([mu_reference; mu_comparison], 'omitnan');
if ~isfinite(lambda_bar) || lambda_bar <= 0
    error('suppfigure11_stats:PoissonMean', ...
        'Invalid expected Poisson count for bin %s.', bin_label);
end
end


function variance = getObservationLevelVariance(glme, specification)
variance = 0;
if ~contains(specification.formula, "(1|ObservationID)")
    return
end
psi = covarianceParameters(glme);
if isempty(psi) || ~isscalar(psi{end})
    error('suppfigure11_stats:OLREVariance', ...
        'Could not identify the ObservationID random-intercept variance.');
end
% ObservationID is the final grouping term in both Poisson formulas.
variance = psi{end}(1, 1);
end


function test_stats = runJointCoefficientTest(glme, mask)
indices = find(mask);
test_stats = struct( ...
    'n_terms', numel(indices), ...
    'coefficient_mask', logical(mask), ...
    'p', NaN, 'F', NaN, 'df1', NaN, 'df2', NaN);
if isempty(indices)
    return
end
H = zeros(numel(indices), numel(mask));
for row = 1:numel(indices)
    H(row, indices(row)) = 1;
end
[p, F, df1, df2] = coefTest(glme, H);
test_stats.p = p;
test_stats.F = F;
test_stats.df1 = df1;
test_stats.df2 = df2;
end


