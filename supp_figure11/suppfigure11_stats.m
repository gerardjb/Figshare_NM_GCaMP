function stats = suppfigure11_stats()
%SUPPFIGURE11_STATS Fit the inferential models for panels B and C.
%
% The models use the raw cell-epoch contributions packaged beside this
% function. Bootstrap replicates used for the plotted confidence intervals
% are deliberately not treated as observations in the inferential models.
%
% Outputs are written to output/supp_figure11:
%   suppfigure11_stats.mat
%   suppfigure11_stats_coefficients.csv
%   suppfigure11_stats_tests.csv
%   suppfigure11_stats_latent_effect_sizes.csv
%   suppfigure11_stats_notes.txt

script_dir = fileparts(mfilename('fullpath'));
repo_root = fileparts(script_dir);
output_dir = fullfile(repo_root, 'output', 'supp_figure11');
if ~isfolder(output_dir)
    mkdir(output_dir);
end

source_files = struct( ...
    'panel_B', fullfile(script_dir, 'panel_B_epoch_metrics.csv'), ...
    'panel_C', fullfile(script_dir, ...
        'panel_C_history_200ms_epoch_contributions.csv'));
validateFiles(source_files);

panel_B_table = readStatsInput(source_files.panel_B, ...
    ["CellID", "CellEpochID", "MethodKey", "Method", "GTSpikeBin"]);
panel_C_table = readStatsInput(source_files.panel_C, ...
    ["CellID", "CellEpochID", "MethodKey", "Method", "HistoryBin"]);
validatePanelBTables(panel_B_table);
validatePanelCTables(panel_C_table);

stats = struct();
stats.source_files = source_files;
stats.generated_by = mfilename;
stats.generated_on = string(datetime('now'));
stats.method_order = ["Biophys_SMC", "MLspike", "PGBAR"];
stats.reference_methods = "Biophys_SMC";
stats.dummy_var_coding = "reference";
stats.subject_id_definition = [ ...
    "CellEpochID is a unique cell-recording-epoch identifier. " + ...
    "CellEpochID is nested within CellID, and each CellEpochID contains " + ...
    "the paired observations from all three methods."];
stats.bootstrap_role = [ ...
    "Paired cell-level bootstrap intervals are used for plotting only. " + ...
    "Bootstrap replicates are not observations in these models."];
stats.latent_effect_size = struct( ...
    'label', "Approximate latent-scale standardized contrast", ...
    'direction', [ ...
        "Positive values indicate more errors for the comparison " + ...
        "method than for Biophys_SMC."], ...
    'binomial_definition', ...
        "log(odds ratio) / sqrt(pi^2/3)", ...
    'poisson_definition', [ ...
        "log(rate ratio) / sqrt(log(1 + 1/lambda_bar) + " + ...
        "observation-level random-intercept variance)"], ...
    'poisson_lambda_definition', [ ...
        "Mean fixed-effect expected count across the reference and " + ...
        "comparison counterfactual predictions in the activity bin, " + ...
        "using the observed offsets."], ...
    'interval_definition', [ ...
        "Plug-in 95% interval obtained by dividing the link-scale " + ...
        "contrast interval by the estimated latent SD; uncertainty in " + ...
        "the denominator is not propagated."], ...
    'primary_effects', [ ...
        "Rate ratios and odds ratios remain the primary effect-size " + ...
        "estimates; latent d values are secondary approximations."], ...
    'references', [ ...
        "Chinn 2000, Statistics in Medicine, DOI:10.1002/1097-0258(20001130)19:22<3127::AID-SIM784>3.0.CO;2-M"; ...
        "Nakagawa, Johnson & Schielzeth 2017, Journal of the Royal Society Interface, DOI:10.1098/rsif.2017.0213"]);
stats.differences_from_figure4_panel_D = [ ...
    "fitglme is used instead of fitlme because the responses are counts " + ...
        "or binomial proportions, not Fisher-Z correlations."; ...
    "False-positive counts use log exposure offsets. Panel B uses epoch " + ...
        "duration and panel C uses seconds spent in each history bin."; ...
    "MATLAB fitglme does not provide a negative-binomial mixed model. " + ...
        "A Poisson-lognormal model is therefore used, with an " + ...
        "observation-level random intercept to absorb extra-Poisson variation."; ...
    "False-negative analyses use the number of ground-truth spikes as " + ...
        "the binomial denominator; rows with no ground-truth spikes are excluded."; ...
    "For the panel C false-negative GLMM only, the 5-8 and 9+ history " + ...
        "bins are combined as 5+. PGBAR had 0 misses among the 49 " + ...
        "ground-truth spikes in the 9+ bin, causing complete separation " + ...
        "in the six-level categorical model. The plotted estimates and " + ...
        "bootstrap intervals retain all six original bins."; ...
    "Separate random intercepts for CellID and CellEpochID preserve both " + ...
        "cell clustering and within-epoch pairing across methods."; ...
    "Generalized mixed models do not use the Satterthwaite option applied " + ...
        "to the Gaussian LME in Figure 4. Tests here use fitglme/coefTest " + ...
        "residual degrees of freedom."; ...
    "Interaction and overall method tests are joint tests of all relevant " + ...
        "coefficients. Per-bin method contrasts are also saved."];

panel_B_table = preparePanelBTable(panel_B_table, stats.method_order);
panel_C_table = preparePanelCTable(panel_C_table, stats.method_order);

panel_B = struct();
panel_B.panel = "B";
panel_B.title = "Errors versus epoch-wise spike count";
panel_B.bin_variable = "GTSpikeBin";
